/**
 * docs/F01_G01_PROGRAM_SELECTION.md 一-2 — why there is no automatic next week, without implying that more
 * answers would unlock one. g01_no_basis: the reports are complete (or differ) but there is no verified basis
 * for an automatic arrangement; g01_missing_conditions: the same, AND some test conditions are missing.
 * @returns {{ kind: "g01_no_basis" | "g01_missing_conditions" | "data_insufficient", missing: string[] }}
 */
export function describeD5NoAutoKind(d5) {
  if (!(d5 && d5.g01NextCycle && d5.g01NextCycle.applied)) return { kind: "data_insufficient", missing: [] };
  const c = d5.comparisonConditions || { reasons: [] };
  const missing = describeComparisonConditionReasons({ reasons: (c.reasons || []).filter((r) => r.kind === "insufficient") });
  return { kind: missing.length ? "g01_missing_conditions" : "g01_no_basis", missing };
}
