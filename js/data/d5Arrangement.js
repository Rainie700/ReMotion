/**
 * docs/F01_G01_PROGRAM_SELECTION.md 一-1 — a not-yet-accepted G01 proposal made under an older decision version
 * (before f01-g01-next-cycle-1.0) is never shown or accepted as a current arrangement, and no confirmation of
 * it carries over: it must be regenerated by redoing the status check (the draft record itself is kept).
 */
export function isOutdatedG01Proposal(proposal) {
  const d5 = (proposal && proposal.d5) || {};
  return !!proposal && proposal.status !== "accepted" && d5.selectedGoalId === "G01"
    && !(d5.g01NextCycle && d5.g01NextCycle.ruleVersion === F01_G01_NEXT_CYCLE_RULE_VERSION);
}
