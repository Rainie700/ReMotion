process.env.TZ = "Asia/Taipei";
import assert from "node:assert/strict";
const memory = new Map();
globalThis.localStorage = { getItem: (k) => memory.get(k) ?? null, setItem: (k, v) => memory.set(k, String(v)), removeItem: (k) => memory.delete(k) };
const M = await import("../js/data/dailyTrainingFeedback.js");
const { dailyTrainingFeedbackService: S } = await import("../js/data/dailyTrainingFeedbackService.js");
const { createCollection } = await import("../js/data/storageService.js");
const V = await import("../js/ui/dailyTrainingFeedbackView.js");
const { readFileSync } = await import("node:fs");
const now = () => new Date("2026-10-23T08:00:00Z");
const input = { patientId: "feedback-p", dateKey: "2026-10-23", effort: "unknown", discomfort: "unknown", note: "", expectedRevision: 0 };
const context = { reportedAt: now().toISOString(), therapistId: "feedback-t", relationId: "feedback-r" };
assert.equal(M.feedbackId("p", "2026-02-30"), null);
assert.equal(M.feedbackId("p/evil", "2026-10-23"), null);
assert.equal(M.latestDailyFeedback(null), null);
assert.ok(V.dailyFeedbackSummary(null).includes("不代表沒有不舒服"));
const unknown = M.buildDailyFeedbackRecord(input, null, context).record;
assert.deepEqual([unknown.reports[0].effort, unknown.reports[0].discomfort], ["unknown", "unknown"]);
assert.equal(M.buildDailyFeedbackRecord({ ...input, effort: "" }, null, context).error, "invalid_input");
assert.equal(M.buildDailyFeedbackRecord({ ...input, discomfort: false }, null, context).error, "invalid_input");
assert.equal(M.buildDailyFeedbackRecord({ ...input, note: "x".repeat(501) }, null, context).error, "invalid_input");
assert.equal(M.buildDailyFeedbackRecord(input, unknown, context).error, "conflict");
let cloud = null;
const commit = async (i, c) => {
  const result = M.buildDailyFeedbackRecord(i, cloud, c);
  if (result.error) throw Object.assign(new Error(result.error), { code: result.error, current: cloud });
  cloud = structuredClone(result.record);
  return result.record;
};
createCollection("therapistPatientRelations").create({ id: "feedback-r", patientId: input.patientId, therapistId: "feedback-t", status: "accepted" });
assert.equal(S.getForDay(input.patientId, input.dateKey), null);
assert.equal((await S.save(input, { now, commit: async () => { throw new Error("offline"); } })).error, "cloud_save_failed");
assert.equal(S.getForDay(input.patientId, input.dateKey), null, "no local success when cloud failed");
const first = await S.save(input, { now, commit });
assert.equal(first.record.revision, 1);
assert.equal(S.listForTherapist("outsider", input.patientId).length, 0);
assert.equal(S.listForTherapist("feedback-t", input.patientId).length, 1);
const old = JSON.stringify(first.record.reports[0]);
const corrected = await S.save({ ...input, expectedRevision: 1, discomfort: "yes", effort: "very_hard", note: '<script>alert("x")</script>' }, { now, commit });
assert.equal(corrected.record.revision, 2);
assert.equal(JSON.stringify(corrected.record.reports[0]), old);
assert.equal(S.getForDay(input.patientId, input.dateKey).reports.length, 2);
assert.equal(createCollection("dailyTrainingFeedback").list().length, 1, "one document per patient/day");
assert.equal((await S.save(input, { now, commit })).error, "conflict");
// A second device saved a correction not yet present in this device's cache.
cloud = M.buildDailyFeedbackRecord({ ...input, expectedRevision: 2, effort: "easy" }, cloud, context).record;
assert.equal((await S.save({ ...input, expectedRevision: 2, discomfort: "no" }, { now, commit })).error, "conflict");
assert.equal(S.getForDay(input.patientId, input.dateKey).revision, 3, "conflict refreshes cache without overwriting the other device");
assert.equal((await S.save({ ...input, dateKey: "2026-10-22" }, { now, commit })).error, "day_changed");
const beforeOther = S.getForDay(input.patientId, input.dateKey);
await S.save({ ...input, patientId: "feedback-other" }, { now, commit: async (i, c) => M.buildDailyFeedbackRecord(i, null, c).record });
assert.deepEqual(S.getForDay(input.patientId, input.dateKey), beforeOther, "account isolation");
createCollection("therapistPatientRelations").update("feedback-r", { status: "completed" });
assert.equal(S.listForTherapist("feedback-t", input.patientId).length, 0, "revoked relation cannot view cached feedback");
const html = V.renderDailyFeedbackCard({ dateKey: input.dateKey, record: corrected.record, editing: true });
assert.ok(html.includes("&lt;script&gt;") && !html.includes('<script>alert'));
assert.ok(!V.renderDailyFeedbackCard({ dateKey: input.dateKey }).includes('value="no" selected'));
assert.ok(V.renderDailyFeedbackHistory([], { cloudStatus: "failed" }).includes("無法確認是否有回報"));
assert.ok(V.renderDailyFeedbackHistory([corrected.record]).includes("&lt;script&gt;"));
const app = readFileSync(new URL("../app.js", import.meta.url), "utf8");
assert.ok(app.includes("${renderDailyTrainingFeedback(patientId)}"));
assert.ok(app.includes("window.saveDailyFeedbackFromUi = saveDailyFeedbackFromUi"));
assert.ok(app.includes("renderDailyFeedbackHistory(dailyTrainingFeedbackService.listForTherapist"));
// No decision inputs or AI scores are written by this feature.
assert.equal(createCollection("recommendationResults").list().length, 0);
assert.equal(createCollection("analysisRecords").list().length, 0);
console.log("dailyTrainingFeedback: validation, append-only corrections, conflict, failure, account and relation isolation, UI escaping passed");
